import { test, expect } from '@playwright/test';
import { createHash } from 'node:crypto';
const readToken = 'local-e2e-catalog-token-1234567890123456789012345';
test('owner can create, edit, publish, revoke, archive and restore a real plugin', async ({page,request})=>{
  const name=`browser-test-${Date.now()}`;
  await page.goto('/admin/plugins');
  await page.getByLabel('Administrator access key').fill('local-e2e-admin-key-12345678901234567890123456789');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('button',{name:'Sign out'})).toBeVisible();
  await page.getByRole('button',{name:'Create plugin',exact:true}).first().click();
  await page.getByLabel('Display name',{exact:true}).fill('Release Assistant');
  await page.getByLabel('Plugin identifier',{exact:true}).fill(name);
  await page.getByRole('textbox',{name:'Description',exact:true}).fill('Prepare a sourced release review.');
  await page.getByLabel('Version',{exact:true}).fill('1.0.0');
  await page.getByRole('button',{name:'MCP servers',exact:true}).click();
  await page.getByLabel('Server configuration JSON').fill(JSON.stringify({'microsoft-docs':{url:'https://learn.microsoft.com/api/mcp'}},null,2));
  await page.getByRole('button',{name:'Skills',exact:true}).click();
  await page.getByRole('button',{name:'Add skill',exact:true}).click();
  await page.getByLabel('Skill name',{exact:true}).fill('release-review');
  await page.getByLabel('When to use this skill',{exact:true}).fill('Use for release reviews');
  await page.getByLabel('Instructions',{exact:true}).fill('Read repository changes. Check documentation. Draft a sourced report. Never publish without an explicit request.');
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Draft saved');
  await page.getByRole('button',{name:'Publish',exact:true}).click();
  await expect(page.getByRole('region',{name:'Review publication'})).toContainText('1 skill and 1 MCP server');
  await page.getByRole('button',{name:'Publish release',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Release published');
  const catalog=await (await request.get('/api/plugins/v1/plugins',{headers:{Authorization:`Bearer ${readToken}`}})).json();
  const published=catalog.plugins.find((p: { name: string; sha256: string })=>p.name===name);expect(published).toBeTruthy();
  const pkg=await request.get(`/api/plugins/v1/plugins/${name}/releases/1.0.0/package`,{headers:{Authorization:`Bearer ${readToken}`}});
  const bytes=await pkg.body();expect(createHash('sha256').update(bytes).digest('hex')).toBe(published.sha256);
  expect(JSON.parse(bytes.toString()).files['skills/release-review/SKILL.md']).toContain('Draft a sourced report');
  const publicResponse=await request.get('/api/plugins/v1/plugins');expect((await publicResponse.json()).plugins.some((p: { name: string; sha256: string })=>p.name===name)).toBe(false);
  await page.getByRole('button',{name:'Overview',exact:true}).click();
  await page.getByRole('textbox',{name:'Description',exact:true}).fill('Updated release review workflow.');
  await page.getByLabel('Version',{exact:true}).fill('1.0.1');
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Draft saved');
  const old=await request.get(`/api/plugins/v1/plugins/${name}/releases/1.0.0/package`,{headers:{Authorization:`Bearer ${readToken}`}});expect(await old.body()).toEqual(bytes);
  await page.getByRole('button',{name:'Publish',exact:true}).click();await page.getByRole('button',{name:'Publish release',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Release published');
  await page.getByRole('button',{name:'Releases',exact:true}).click();
  await expect(page.getByText('1.0.1',{exact:true}).first()).toBeVisible();
  await page.screenshot({path:'/tmp/supercharge-plugin-admin-desktop.png',fullPage:true});
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Revoke',exact:true}).last().click();
  await expect(page.getByRole('status')).toContainText('Release revoked');
  await page.getByRole('button',{name:'Archive plugin',exact:true}).click();
  await page.getByRole('region',{name:'Review archive'}).getByRole('button',{name:'Archive plugin',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Plugin archived');
  expect((await request.get(`/api/plugins/v1/plugins/${name}/releases/1.0.1/package`,{headers:{Authorization:`Bearer ${readToken}`}})).status()).toBe(404);
  await page.getByRole('button',{name:'Restore plugin',exact:true}).click();
  await expect(page.getByRole('button',{name:'Archive plugin',exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Overview',exact:true}).click();
  await expect(page.getByLabel('Display name',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'/tmp/supercharge-plugin-admin-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await expect(page.getByLabel('Administrator access key')).toBeVisible();
});


test('admin dashboard shares its password session with plugin management', async ({ page }) => {
  await page.goto('/admin');
  await page.getByLabel('Administrator password').fill('incorrect-password');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page.getByText('Invalid administrator access key', { exact: true })).toBeVisible();
  await page.getByLabel('Administrator password').fill('local-e2e-admin-key-12345678901234567890123456789');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page.getByRole('heading', { name: 'Welcome to your control center.' })).toBeVisible();
  await page.getByRole('link', { name: /Plugins/ }).click();
  await expect(page).toHaveURL(/\/admin\/plugins$/);
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('link', { name: 'Admin', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome to your control center.' })).toBeVisible();
  await page.getByRole('button', { name: 'Sign out' }).click();
  await expect(page.getByLabel('Administrator password')).toBeVisible();
  await page.goto('/admin/plugins');
  await expect(page.getByLabel('Administrator access key')).toBeVisible();
});
